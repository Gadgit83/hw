/* SDL_main for Hedge Party: starts the IPC server, then runs the engine on this thread.
 *
 * Diagnostics, because the engine was written for a desktop and is quiet on a phone:
 *  - stdout and stderr (the engine's console output) are piped into logcat, tag HW_Engine.
 *  - The engine ends a failed start with exit(), which takes the whole process down without
 *    a word. The error it sends over IPC ('E' message) and an atexit hook are written to
 *    files/logs/last_error.txt so the Java side can show a reason on the next screen.
 *  - A normal end (engine returned 0) removes files/logs/game_running, the marker that
 *    GameActivity creates, so a marker left behind means the game did not finish cleanly. */
#include <SDL.h>
#include <android/log.h>
#include <errno.h>
#include <pthread.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <unistd.h>

#include "hp.h"

#define TAG "HedgeParty"
#define LOGI(...) __android_log_print(ANDROID_LOG_INFO, TAG, __VA_ARGS__)
#define LOGE(...) __android_log_print(ANDROID_LOG_ERROR, TAG, __VA_ARGS__)

/* Entry point generated by pas2c from hwengine.pas (HWLIBRARY build). */
extern int hwengine_RunEngine(int argc, char **argv);

static char g_error_path[1100];
static char g_marker_path[1100];
static volatile int g_error_set;
static volatile int g_clean;

/* Records the first reason only; later ones are usually consequences of it. */
static void record_error(const char *message)
{
    if (!__sync_bool_compare_and_swap(&g_error_set, 0, 1)) return;
    LOGE("recording error: %s", message);
    FILE *f = fopen(g_error_path, "w");
    if (!f) {
        LOGE("cannot write %s: %s", g_error_path, strerror(errno));
        return;
    }
    fputs(message, f);
    fputc('\n', f);
    fclose(f);
}

static void on_engine_error(const char *message)
{
    char line[320];
    snprintf(line, sizeof line, "Engine error: %s", message);
    record_error(line);
}

/* Runs when the engine calls exit() itself (fatal error path). The IPC thread may not have
 * read the engine's 'E' message yet, so give it a moment before assuming there was none. */
static void on_exit_hook(void)
{
    if (g_clean) return;
    for (int i = 0; i < 40 && !g_error_set; i++) usleep(10000);
    record_error("The game engine ended the program unexpectedly (it called exit without a message).");
}

static void *log_pump(void *arg)
{
    int fd = (int)(intptr_t)arg;
    char buf[1024];
    size_t used = 0;
    for (;;) {
        ssize_t n = read(fd, buf + used, sizeof buf - 1 - used);
        if (n <= 0) {
            if (n < 0 && errno == EINTR) continue;
            break;
        }
        used += (size_t)n;
        buf[used] = 0;
        char *start = buf, *nl;
        while ((nl = strchr(start, '\n')) != NULL) {
            *nl = 0;
            if (*start) __android_log_write(ANDROID_LOG_INFO, "HW_Engine", start);
            start = nl + 1;
        }
        used = (size_t)(buf + used - start);
        if (used > 0 && start != buf) memmove(buf, start, used);
        if (used >= sizeof buf - 1) {
            buf[used] = 0;
            __android_log_write(ANDROID_LOG_INFO, "HW_Engine", buf);
            used = 0;
        }
    }
    return NULL;
}

static void redirect_stdio(void)
{
    static int done;
    int fds[2];
    pthread_t t;
    if (done) return;
    done = 1;
    if (pipe(fds)) return;
    fflush(stdout);
    fflush(stderr);
    dup2(fds[1], STDOUT_FILENO);
    dup2(fds[1], STDERR_FILENO);
    close(fds[1]);
    setvbuf(stdout, NULL, _IOLBF, 0);
    setvbuf(stderr, NULL, _IONBF, 0);
    if (pthread_create(&t, NULL, log_pump, (void *)(intptr_t)fds[0]) == 0) pthread_detach(t);
}

int SDL_main(int argc, char **argv)
{
    (void)argc;
    (void)argv;
    const char *base = SDL_AndroidGetInternalStoragePath();
    char config[1024], data[1024], user[1024], port[16], w[16], h[16], probe[1100];
    SDL_Rect bounds = { 0, 0, 1280, 720 };
    struct stat st;

    redirect_stdio();
    if (!base) {
        LOGE("no internal storage path");
        return 1;
    }
    snprintf(g_error_path, sizeof g_error_path, "%s/logs/last_error.txt", base);
    snprintf(g_marker_path, sizeof g_marker_path, "%s/logs/game_running", base);
    atexit(on_exit_hook);
    hp_ipc_set_error_handler(on_engine_error);

    snprintf(config, sizeof config, "%s/game.ipc", base);
    snprintf(data, sizeof data, "%s/Data", base);
    snprintf(user, sizeof user, "%s/user", base);

    /* Cheap checks that turn the commonest setup mistakes into a readable message. */
    snprintf(probe, sizeof probe, "%s/Locale/en.txt", data);
    if (stat(probe, &st) != 0) {
        char m[1300];
        snprintf(m, sizeof m, "Game data is missing (%s not found). Reinstall or clear the app storage.", probe);
        record_error(m);
        return 3;
    }
    if (stat(config, &st) != 0) {
        char m[1300];
        snprintf(m, sizeof m, "The game setup file is missing (%s).", config);
        record_error(m);
        return 3;
    }
    mkdir(user, 0771);

    int p = hp_ipc_start(config);
    if (p < 0) {
        record_error("Could not start the local game setup server (socket error).");
        return 2;
    }
    snprintf(port, sizeof port, "%d", p);

    if (SDL_Init(SDL_INIT_VIDEO) == 0) {
        SDL_GetDisplayBounds(0, &bounds);
        SDL_QuitSubSystem(SDL_INIT_VIDEO);
    } else {
        LOGE("SDL_Init video failed: %s", SDL_GetError());
    }
    snprintf(w, sizeof w, "%d", bounds.w);
    snprintf(h, sizeof h, "%d", bounds.h);

    /* In the HWLIBRARY build the engine parses argv from index 0, so slot 0 holds a
     * harmless option instead of a program name. */
    char *args[] = {
        "--no-holiday-silliness", "--internal", "--port", port,
        "--prefix", data, "--user-prefix", user,
        "--width", w, "--height", h,
        "--fullscreen-width", w, "--fullscreen-height", h, "--fullscreen",
        "--locale", "en.txt", "--nodampen", "--nick", "Player",
    };
    int n = (int)(sizeof args / sizeof args[0]);
    LOGI("starting engine, ipc port %d, %sx%s, data %s", p, w, h, data);
    int rc = hwengine_RunEngine(n, args);
    LOGI("engine returned %d", rc);
    hp_ipc_join();
    if (rc == 0) {
        g_clean = 1;
        unlink(g_marker_path);
    } else {
        char m[96];
        snprintf(m, sizeof m, "The game engine stopped with code %d.", rc);
        record_error(m);
    }
    return rc;
}
