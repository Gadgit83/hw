#!/usr/bin/env python3
"""Regenerates app/src/main/java/org/hedgewars/android/SchemeData.java from the Qt frontend sources.

The built-in game schemes (rules presets) come from QTfrontend/model/gameSchemeModel.cpp and the
built-in weapon sets from QTfrontend/weapons.h and QTfrontend/hwconsts.cpp.in of the engine
checkout, so the values are the ones the desktop game sends. The output is committed; run this only
when the engine's presets change.

Usage: gen-schemes.py [path to the engine checkout]   (default: the repository root, ../..)
"""
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
hw = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "..", "..")
out = os.path.join(here, "..", "app", "src", "main", "java", "org", "hedgewars", "android", "SchemeData.java")

model = open(os.path.join(hw, "QTfrontend", "model", "gameSchemeModel.cpp"), encoding="utf-8").read()

# Names, in the order of predefSchemesNames.
names_block = re.search(r"predefSchemesNames = QStringList\(\)(.*?);", model, re.S).group(1)
names = re.findall(r'<<\s*"([^"]*)"', names_block)

# Every QList<QVariant> block: "<id> << ... ;" holding 45 values (name first).
blocks = {}
for m in re.finditer(r"QList<QVariant>\s+(\w+)\s*(?:=\s*QList<QVariant>\(\))?\s*;?\s*\1?\s*(<<.*?;)", model, re.S):
    pass


def values_of(text):
    vals = []
    for item in re.finditer(r"<<\s*(?:QVariant\(([^)]*)\)|predefSchemesNames\[(\d+)\])", text):
        if item.group(2) is not None:
            vals.append(("name", int(item.group(2))))
        else:
            vals.append(("v", item.group(1).strip()))
    return vals


# defaultScheme is a file-level definition, the rest are local variables followed by "name\n << ...".
schemes = []
m = re.search(r"QList<QVariant> defaultScheme = QList<QVariant>\(\)(.*?);", model, re.S)
schemes.append(("Default", values_of(m.group(1))))
order = re.search(r"schemes\.append\(defaultScheme\);(.*?)\n\s*\n", model, re.S).group(1)
order_ids = re.findall(r"schemes\.append\((\w+)\);", "schemes.append(defaultScheme);" + order)
for var in order_ids[1:]:
    m = re.search(r"QList<QVariant> %s;\s*%s(.*?);" % (var, var), model, re.S)
    if not m:
        raise SystemExit("scheme block %s not found" % var)
    schemes.append((var, values_of(m.group(1))))

rows = []
for idx, (var, vals) in enumerate(schemes):
    assert len(vals) == 45, (var, len(vals))
    name = names[idx] if idx < len(names) else var
    if vals[0][0] == "name":
        assert names[vals[0][1]] == name, (var, name)
    flags = ""
    nums = []
    for i in range(1, 26):
        v = vals[i][1]
        assert v in ("true", "false"), (var, i, v)
        flags += "1" if v == "true" else "0"
    for i in range(26, 44):
        nums.append(int(vals[i][1]))
    rows.append((name, flags, nums))

# Weapon sets.
wh = open(os.path.join(hw, "QTfrontend", "weapons.h"), encoding="utf-8").read()
defs = {}
for m in re.finditer(r'#define\s+AMMOLINE_(\w+?)_(QT|PROB|DELAY|CRATE)\s+"([01-9]+)"', wh):
    defs.setdefault(m.group(1), {})[m.group(2)] = m.group(3)
consts = open(os.path.join(hw, "QTfrontend", "hwconsts.cpp.in"), encoding="utf-8").read()
sets = []
for m in re.finditer(r'qMakePair\(QString\("([^"]+)"\),\s*(?:\*cDefaultAmmoStore|QString\(\s*AMMOLINE_(\w+?)_QT)', consts):
    key = m.group(2) or "DEFAULT"
    d = defs[key]
    assert all(len(d[k]) == 60 for k in ("QT", "PROB", "DELAY", "CRATE")), key
    sets.append((m.group(1), d["QT"] + d["PROB"] + d["DELAY"] + d["CRATE"]))

with open(out, "w", encoding="utf-8") as f:
    f.write("package org.hedgewars.android;\n\n")
    f.write("/**\n * Built-in game schemes and weapon sets of the desktop game. GENERATED by scripts/gen-schemes.py from\n")
    f.write(" * QTfrontend/model/gameSchemeModel.cpp, QTfrontend/weapons.h and QTfrontend/hwconsts.cpp.in; do not edit.\n")
    f.write(" * Flags are the 25 booleans (scheme entries 1 to 25) as 0 or 1, values are entries 26 to 43.\n */\n")
    f.write("final class SchemeData {\n    private SchemeData() { }\n\n")
    f.write("    static final String[] SCHEME_NAMES = {\n")
    for n, _, _ in rows:
        f.write('        "%s",\n' % n)
    f.write("    };\n\n    static final String[] SCHEME_FLAGS = {\n")
    for n, fl, _ in rows:
        f.write('        "%s", // %s\n' % (fl, n))
    f.write("    };\n\n    static final int[][] SCHEME_VALUES = {\n")
    for n, _, nums in rows:
        f.write("        { %s }, // %s\n" % (", ".join(str(x) for x in nums), n))
    f.write("    };\n\n    static final String[] WEAPON_NAMES = {\n")
    for n, _ in sets:
        f.write('        "%s",\n' % n)
    f.write("    };\n\n    /** Per set: loadout, probability, delay, crate (60 digits each). */\n    static final String[] WEAPON_STRINGS = {\n")
    for n, s in sets:
        f.write('        "%s", // %s\n' % (s, n))
    f.write("    };\n}\n")
print("wrote", out, len(rows), "schemes,", len(sets), "weapon sets")
